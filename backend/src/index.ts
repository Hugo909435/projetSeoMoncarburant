const PUBLIC_READ_ACTIONS = [
  'api::article.article.find',
  'api::article.article.findOne',
  'api::author.author.find',
  'api::author.author.findOne',
  'api::category.category.find',
  'api::category.category.findOne',
  'api::site-setting.site-setting.find',
  'api::static-page.static-page.find',
  'api::static-page.static-page.findOne',
]

async function grantPublicReadPermissions(strapi: StrapiInstance) {
  const publicRole = await strapi.query('plugin::users-permissions.role').findOne({
    where: { type: 'public' },
  })

  if (!publicRole) {
    strapi.log.warn('[Permissions] Role public introuvable, permissions ignorees.')
    return
  }

  for (const action of PUBLIC_READ_ACTIONS) {
    const existingPermission = await strapi
      .query('plugin::users-permissions.permission')
      .findOne({
        where: {
          action,
          role: publicRole.id,
        },
      })

    if (!existingPermission) {
      await strapi.query('plugin::users-permissions.permission').create({
        data: {
          action,
          role: publicRole.id,
        },
      })
    }
  }
}

